import { randomUUID } from 'node:crypto';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { Response } from 'express';
import { AppError } from '../errors.js';

export type FileKind = 'pdf' | 'png' | 'jpeg';

const KINDS: Record<FileKind, { ext: string; mime: string; magic: number[] }> = {
  pdf: { ext: 'pdf', mime: 'application/pdf', magic: [0x25, 0x50, 0x44, 0x46, 0x2d] }, // %PDF-
  png: { ext: 'png', mime: 'image/png', magic: [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a] },
  jpeg: { ext: 'jpg', mime: 'image/jpeg', magic: [0xff, 0xd8, 0xff] },
};

/** Storage keys are generated by the server and never contain user input. */
const KEY_PATTERN =
  /^[0-9a-f]{2}\/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(pdf|png|jpg)$/;

export interface StoredFile {
  key: string;
  size: number;
  contentType: string;
}

export interface PutOptions {
  data: Buffer;
  /** Which content types the caller accepts. The actual bytes must match one of them. */
  allowed: FileKind[];
  maxBytes: number;
}

export interface FileStorage {
  put(options: PutOptions): Promise<StoredFile>;
  get(key: string): Promise<{ data: Buffer; contentType: string }>;
  remove(key: string): Promise<void>;
}

/** Identifies a file by its leading bytes; the client-supplied name or MIME type is never trusted. */
export function detectKind(data: Buffer): FileKind | null {
  for (const [kind, spec] of Object.entries(KINDS) as [FileKind, (typeof KINDS)[FileKind]][]) {
    if (data.length >= spec.magic.length && spec.magic.every((b, i) => data[i] === b)) return kind;
  }
  return null;
}

const invalidFile = (message: string) => new AppError(422, 'INVALID_FILE', message);

/**
 * Stores files on local disk under `rootDir`, which must be outside any web-served directory.
 * Files are written with random names, never overwritten, and only read back through validated keys.
 */
export class LocalFileStorage implements FileStorage {
  private readonly root: string;
  constructor(rootDir: string) {
    this.root = path.resolve(rootDir);
  }

  async put({ data, allowed, maxBytes }: PutOptions): Promise<StoredFile> {
    if (data.length === 0) throw invalidFile('File is empty');
    if (data.length > maxBytes)
      throw new AppError(413, 'PAYLOAD_TOO_LARGE', `File exceeds the ${maxBytes} byte limit`);
    const kind = detectKind(data);
    if (!kind || !allowed.includes(kind)) {
      throw invalidFile(`Unsupported file type; allowed: ${allowed.join(', ')}`);
    }
    const id = randomUUID();
    const key = `${id.slice(0, 2)}/${id}.${KINDS[kind].ext}`;
    const full = this.resolveKey(key);
    await mkdir(path.dirname(full), { recursive: true, mode: 0o750 });
    await writeFile(full, data, { flag: 'wx', mode: 0o640 });
    return { key, size: data.length, contentType: KINDS[kind].mime };
  }

  async get(key: string): Promise<{ data: Buffer; contentType: string }> {
    const full = this.resolveKey(key);
    try {
      return { data: await readFile(full), contentType: contentTypeForKey(key) };
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === 'ENOENT')
        throw new AppError(404, 'NOT_FOUND', 'File not found');
      throw err;
    }
  }

  async remove(key: string): Promise<void> {
    await rm(this.resolveKey(key), { force: true });
  }

  /** Rejects anything that is not a server-generated key, then double-checks the resolved path stays inside the root. */
  private resolveKey(key: string): string {
    if (!KEY_PATTERN.test(key)) throw new AppError(400, 'INVALID_FILE_KEY', 'Invalid file key');
    const full = path.resolve(this.root, key);
    if (!full.startsWith(this.root + path.sep))
      throw new AppError(400, 'INVALID_FILE_KEY', 'Invalid file key');
    return full;
  }
}

function contentTypeForKey(key: string): string {
  const ext = key.slice(key.lastIndexOf('.') + 1);
  return Object.values(KINDS).find((k) => k.ext === ext)?.mime ?? 'application/octet-stream';
}

/** Makes a download file name safe for use in a header (no path separators, quotes or control characters). */
export function safeDownloadName(name: string, fallback = 'download'): string {
  const cleaned = name
    .replace(/[^\w.\- ]+/g, '_')
    .replace(/^\.+/, '')
    .trim()
    .slice(0, 100);
  return cleaned || fallback;
}

/**
 * Sends a stored file as a download. Callers must have authorized the user for this file first.
 * Headers force download (never inline rendering), forbid MIME sniffing and caching by shared caches.
 */
export async function sendStoredFile(
  res: Response,
  storage: FileStorage,
  key: string,
  downloadName: string,
): Promise<void> {
  const { data, contentType } = await storage.get(key);
  res
    .status(200)
    .set({
      'Content-Type': contentType,
      'Content-Length': String(data.length),
      'Content-Disposition': `attachment; filename="${safeDownloadName(downloadName)}"`,
      'X-Content-Type-Options': 'nosniff',
      'Cache-Control': 'private, no-store',
    })
    .end(data);
}
